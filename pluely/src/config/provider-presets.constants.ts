// Flattened prefix → provider mapping, sorted by prefix length (longest first)
export const KEY_PREFIX_MAP: KeyPrefixMapEntry[] = Object.values(PROVIDER_PRESETS)
  .flatMap((preset) =>
    preset.keyPrefixes
      .filter((kp) => kp.confidence > 0)
      .map((kp) => ({
        prefix: kp.prefix,
        providerId: preset.id,
        confidence: kp.confidence,
      }))
  )
  .sort((a, b) => b.prefix.length - a.prefix.length);

